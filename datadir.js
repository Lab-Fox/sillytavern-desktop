// Where the app keeps its data (settings, logs, logins, add-ons).
//
// Normally that is a folder next to the app: "SillyTavern Desktop Data"
// beside the install folder (updates wipe the install folder itself), or
// beside the portable exe. No pointer file anywhere: the data follows the
// app, survives updates and a Windows reinstall, and stays off C: when the
// app is off C:. Older copies keep %APPDATA%\SillyTavern Desktop until the
// user moves it (Settings → About), and an app on C: keeps using it.
//
// This runs before Electron is ready, so it is plain fs and fully sync.
import fs from 'fs';
import path from 'path';
import { onSystemDrive } from './folders.js';

export const DATA_NAME = 'SillyTavern Desktop Data';
export const MOVE_FILE = 'move-beside.json';   // in the old folder: "copy me beside the app at the next start"
export const MOVED_FROM = 'moved-from.json';   // in the new folder: where the old data still is
export const MOVE_FAILED = 'move-failed.json'; // in the old folder: why the last move didn't happen

// Regenerated by Chromium, so never copied. Checked against every folder name.
const SKIP = new Set(['cache', 'code cache', 'gpucache', 'dawngraphitecache', 'dawnwebgpucache', 'shadercache',
    'grshadercache', 'crashpad', 'cachestorage']);
const SKIP_FILES = new Set([MOVE_FILE, MOVE_FAILED, 'lockfile', 'devtoolsactiveport', 'singletonlock', 'singletoncookie', 'singletonsocket'].map(s => s.toLowerCase()));

export function besideDir({ exePath, portableDir }) {
    const holder = portableDir || path.win32.dirname(path.win32.dirname(exePath));
    return path.win32.join(holder, DATA_NAME);
}

// → { kind: 'flag' | 'appdata' | 'beside' | 'move', dir, beside }
// flag: --user-data-dir given (Electron's choice stays); move: copy appData
// beside first (runMove), then use beside.
export function resolveDataDir({ argv, exePath, portableDir, appData, packaged, env = process.env, exists = fs.existsSync }) {
    if (argv.some(a => a.startsWith('--user-data-dir'))) return { kind: 'flag', dir: null, beside: null };
    if (!packaged) return { kind: 'appdata', dir: appData, beside: null };
    const beside = besideDir({ exePath, portableDir });
    if (exists(beside)) return { kind: 'beside', dir: beside, beside };
    if (exists(path.join(appData, MOVE_FILE))) return { kind: 'move', dir: appData, beside };
    if (exists(path.join(appData, 'settings.json'))) return { kind: 'appdata', dir: appData, beside };
    if (onSystemDrive(beside, env)) return { kind: 'appdata', dir: appData, beside };
    return { kind: 'beside', dir: beside, beside };
}

// Copies the data that matters (no caches) into a new, empty folder, then
// checks every file arrived with the same size. On any problem the new folder
// is removed and the old one is untouched. → { ok, files, bytes, error }
export function copyData(from, to, { failAfter = -1 } = {}) {
    if (fs.existsSync(to) && fs.readdirSync(to).length) return { ok: false, error: `${to} already has files in it` };
    const list = [];
    const walk = (dir, rel) => {
        for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
            const name = e.name.toLowerCase();
            if (e.isDirectory()) { if (!SKIP.has(name)) walk(path.join(dir, e.name), path.join(rel, e.name)); }
            else if (e.isFile() && !SKIP_FILES.has(name)) list.push(path.join(rel, e.name));
        }
    };
    let bytes = 0;
    try {
        walk(from, '');
        list.forEach((rel, i) => {
            if (i === failAfter) throw new Error('test failure');
            const dst = path.join(to, rel);
            fs.mkdirSync(path.dirname(dst), { recursive: true });
            fs.copyFileSync(path.join(from, rel), dst);
        });
        if (failAfter === list.length) throw new Error('test failure');
        for (const rel of list) {
            const a = fs.statSync(path.join(from, rel)).size, b = fs.statSync(path.join(to, rel)).size;
            if (a !== b) throw new Error(`${rel} did not copy completely`);
            bytes += a;
        }
        return { ok: true, files: list.length, bytes };
    } catch (e) {
        try { fs.rmSync(to, { recursive: true, force: true }); } catch { /* best effort */ }
        return { ok: false, error: e.message };
    }
}

// The move asked for in the last run. → the folder to use.
export function runMove(appData, beside) {
    const r = copyData(appData, beside);
    if (r.ok) {
        fs.writeFileSync(path.join(beside, MOVED_FROM), JSON.stringify({ from: appData, at: new Date().toISOString(), files: r.files, bytes: r.bytes }));
        fs.rmSync(path.join(appData, MOVE_FILE), { force: true });
        fs.rmSync(path.join(appData, MOVE_FAILED), { force: true });
        return beside;
    }
    fs.rmSync(path.join(appData, MOVE_FILE), { force: true });
    fs.writeFileSync(path.join(appData, MOVE_FAILED), JSON.stringify({ to: beside, error: r.error, at: new Date().toISOString() }));
    return appData;
}

// Size of a folder's files (for "the old data takes N MB").
export function folderBytes(dir) {
    let n = 0;
    const walk = d => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else if (e.isFile()) n += fs.statSync(p).size; } };
    try { walk(dir); } catch { /* gone or no access */ }
    return n;
}
