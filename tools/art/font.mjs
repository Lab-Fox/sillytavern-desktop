// Draws text at (x, y) = top left; returns the width. `gap` = pixels between letters.
export function text(c, font, str, x, y, color, { gap = 1, scale = 1 } = {}) {
    let cx = x;
    for (const ch of str) {
        const rows = font[ch] || font[ch.toUpperCase()];
        if (!rows) throw new Error(`no glyph for "${ch}"`);
        rows.forEach((r, j) => [...r].forEach((p, i) => { if (p === '#') c.rect(cx + i * scale, y + j * scale, scale, scale, color); }));
        cx += (rows[0].length + gap) * scale;
    }
    return cx - x - gap * scale;
}
export const measure = (font, str, { gap = 1, scale = 1 } = {}) => text(new Canvas(1, 1), font, str, 0, 0, null, { gap, scale });
