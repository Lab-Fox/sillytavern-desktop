// preload.js — safe IPC bridge for the launcher UI
const { contextBridge, ipcRenderer, webUtils, webFrame } = require('electron');

const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
const on = channel => cb => ipcRenderer.on(channel, (_e, ...args) => cb(...args));

contextBridge.exposeInMainWorld('desktop', {
    // server
    getState: () => invoke('get-state'),
    startServer: () => invoke('start-server'),
    stopServer: () => invoke('stop-server'),
    openST: () => invoke('open-st'),
    minimizeST: () => invoke('minimize-st'),
    openInBrowser: () => invoke('open-in-browser'),
    startClassic: () => invoke('start-classic'),
    // version & maintenance
    stInfo: () => invoke('st-info'),
    checkUpdates: () => invoke('check-updates'),
    update: () => invoke('update'),
    repair: kind => invoke('repair', kind),
    switchBranch: branch => invoke('switch-branch', branch),
    healthCheck: () => invoke('health-check'),
    // backups
    backup: () => invoke('backup'),
    listBackups: () => invoke('list-backups'),
    restoreBackup: (name, where) => invoke('restore-backup', name, where),
    deleteBackup: (name, where) => invoke('delete-backup', name, where),
    // scheduled backups
    backupSchedule: () => invoke('backup-schedule'),
    backupScheduleSave: o => invoke('backup-schedule-save', o),
    backupSchedulePick: () => invoke('backup-schedule-pick'),
    backupScheduleRun: () => invoke('backup-schedule-run'),
    backupScheduleDismiss: dir => invoke('backup-schedule-dismiss', dir),
    openBackupDest: () => invoke('open-backup-dest'),
    // import (drag & drop, Open with)
    pathsOf: files => [...files].map(f => webUtils.getPathForFile(f)).filter(Boolean),
    importPending: () => invoke('import-pending'),
    importClassify: paths => invoke('import-classify', paths),
    importRun: o => invoke('import-run', o),
    // extensions
    listExtensions: fetch => invoke('list-extensions', fetch),
    updateExtensions: paths => invoke('update-extensions', paths),
    extCatalog: fresh => invoke('ext-catalog', fresh),
    extUndo: onlyPath => invoke('ext-undo', onlyPath),
    extSearch: q => invoke('ext-search', q),
    extInstall: id => invoke('ext-install', id),
    reloadST: () => invoke('reload-st'),
    openUrl: url => invoke('open-url', url),
    kits: () => invoke('kits'),
    kitSave: (name, description) => invoke('kit-save', name, description),
    kitImport: () => invoke('kit-import'),
    kitExport: id => invoke('kit-export', id),
    kitDelete: id => invoke('kit-delete', id),
    kitInstall: (id, urls, exact) => invoke('kit-install', id, urls, exact),
    // setup & install location
    setupState: () => invoke('setup-state'),
    useInstall: dir => invoke('use-install', dir),
    browseInstall: () => invoke('browse-install'),
    setupReady: () => invoke('setup-ready'),
    installRequirements: () => invoke('install-requirements'),
    setAppPreview: on => invoke('set-app-preview', on),
    remotes: () => invoke('remotes'),
    remoteSave: o => invoke('remote-save', o),
    remoteDelete: id => invoke('remote-delete', id),
    remoteProbe: url => invoke('remote-probe', url),
    remoteCheckUrl: url => invoke('remote-check-url', url),
    remoteOpen: id => invoke('remote-open', id),
    uiFonts: () => invoke('ui-fonts'),
    setUiFont: o => invoke('set-ui-font', o),
    setZoom: pct => webFrame.setZoomFactor(Math.min(1.5, Math.max(0.8, pct / 100))),
    runtimeLatest: () => invoke('runtime-latest'),
    runtimeInstall: () => invoke('runtime-install'),
    runtimeUse: on => invoke('runtime-use', on),
    runtimeRemove: () => invoke('runtime-remove'),
    updateBackend: () => invoke('update-backend'),
    moveST: () => invoke('move-st'),
    // profiles
    profiles: () => invoke('profiles'),
    profileUse: id => invoke('profile-use', id),
    profileSave: p => invoke('profile-save', p),
    profileDelete: id => invoke('profile-delete', id),
    profileBrowse: from => invoke('profile-browse', from),
    profilesAddFound: () => invoke('profiles-add-found'),
    profileOpenAlongside: id => invoke('profile-open-alongside', id),
    profileOpenFolder: id => invoke('profile-open-folder', id),
    onProfiles: on('profiles'),
    // downloading SillyTavern
    stVersions: fresh => invoke('st-versions', fresh),
    downloadTarget: (parent, folder) => invoke('download-target', parent, folder),
    downloadDefaults: () => invoke('download-defaults'),
    pickParent: from => invoke('pick-parent', from),
    stDownload: o => invoke('st-download', o),
    stDownloadCancel: () => invoke('st-download-cancel'),
    openStRelease: v => invoke('open-st-release', v),
    onStDownload: on('st-download'),
    // change history ("What's new")
    history: id => invoke('history', id),
    historyUnseen: () => invoke('history-unseen'),
    historySeen: id => invoke('history-seen', id),
    stIncoming: () => invoke('st-incoming'),
    onHistory: on('history'),
    // migrating data
    migFolders: () => invoke('mig-folders'),
    migBrowse: () => invoke('mig-browse'),
    migScan: o => invoke('mig-scan', o),
    migPreview: (id, keys, policy) => invoke('mig-preview', id, keys, policy),
    migRun: o => invoke('mig-run', o),
    migCancel: () => invoke('mig-cancel'),
    migJournals: dir => invoke('mig-journals', dir),
    migUndo: (dir, id) => invoke('mig-undo', dir, id),
    onMigProgress: on('mig-progress'),
    // themes
    listThemes: () => invoke('list-themes'),
    setTheme: id => invoke('set-theme', id),
    saveTheme: (theme, id) => invoke('save-theme', theme, id),
    deleteTheme: id => invoke('delete-theme', id),
    importTheme: () => invoke('import-theme'),
    exportTheme: id => invoke('export-theme', id),
    stLogo: () => invoke('st-logo'),
    // places, links, misc
    openPlace: key => invoke('open-place', key),
    openLink: key => invoke('open-link', key),
    copyLogs: () => invoke('copy-logs'),
    saveSettings: s => invoke('save-settings', s),
    setLayer: mode => invoke('set-layer', mode),
    setTabs: on => invoke('set-tabs', on),
    // phone & tablet access
    lanInfo: () => invoke('lan-info'),
    lanSave: s => invoke('lan-save', s),
    // updates of this app
    appUpdateState: () => invoke('app-update-state'),
    appUpdateCheck: () => invoke('app-update-check'),
    appUpdateDownload: () => invoke('app-update-download'),
    appUpdateInstall: () => invoke('app-update-install'),
    onAppUpdate: on('app-update'),
    // desktop extensions
    extList: () => invoke('ext:list'),
    extSetEnabled: (id, on) => invoke('ext:set-enabled', id, on),
    extReload: () => invoke('ext:reload'),
    extPanel: id => invoke('ext:panel', id),
    extInvoke: (id, channel, ...args) => invoke('ext:invoke', id, channel, args),
    extAddExample: () => invoke('ext:add-example'),
    // events
    onLog: on('server-log'),
    onStarted: on('server-started'),
    onStopped: on('server-stopped'),
    onBusy: on('busy'),
    onRefresh: on('refresh'),
    onTheme: on('theme'),
    onSettings: on('settings'),
    onWindows: on('st-windows'),
    onBackupSchedule: on('backup-schedule'),
    onRuntimeProgress: on('runtime-progress'),
    onImportFiles: on('import-files'),
});
